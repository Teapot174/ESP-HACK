static void drawXbm(DisplayType& display, int16_t x, int16_t y,
                    uint8_t width, uint8_t height, const uint8_t* bitmap,
                    uint16_t color = SH110X_WHITE) {
  const uint8_t bytesPerRow = (width + 7) / 8;
  for (byte row = 0; row < height; ++row) {
    for (byte column = 0; column < width; ++column) {
      if (bitmap[row * bytesPerRow + column / 8] & (1 << (column & 7))) {
        display.drawPixel(x + column, y + row, color);
      }
    }
  }
}

static void drawIcon(DisplayType& display, byte item, int16_t x, int16_t y,
                     uint16_t color = SH110X_WHITE, bool listOffsets = true) {
  const MenuIcon& icon = *menuIcons[item];
  const byte frame = animationFrames[item] % icon.frameCount;
  const int16_t centeredX = x + 7 - icon.width / 2
    + (listOffsets ? ((item == 0 ? 1 : 0) + (item == 1 ? 2 : 0)) : 0);
  const int16_t centeredY = y + 7 - icon.height / 2;
  drawXbm(display, centeredX, centeredY, icon.width, icon.height, icon.frames[frame], color);
}

static int16_t getScrollbarY(DisplayType& display, byte position, byte total) {
  if (!total) return 0;
  return static_cast<int16_t>(static_cast<float>(display.height()) * position / total);
}

static void drawScrollbar(DisplayType& display, byte position, byte total, int16_t thumbY = -1) {
  const size_t width = display.width();
  const size_t height = display.height();

  display.fillRect(width - 3, 0, 3, height, SH110X_BLACK);
  for (size_t y = 0; y < height; y += 2) {
    display.drawPixel(width - 2, y, SH110X_WHITE);
  }
  if (total) {
    const float blockHeight = static_cast<float>(height) / total;
    if (thumbY < 0) thumbY = getScrollbarY(display, position, total);
    display.fillRect(
      width - 3,
      thumbY,
      3,
      blockHeight > 1.0f ? blockHeight : 1.0f,
      SH110X_WHITE);
  }
}

static void drawFrame(DisplayType& display) {
  display.drawLine(2, 21, 121, 21, SH110X_WHITE);
  display.drawLine(1, 40, 123, 40, SH110X_WHITE);
  display.drawLine(2, 41, 122, 41, SH110X_WHITE);
  display.drawLine(0, 23, 0, 39, SH110X_WHITE);
  display.drawLine(122, 22, 122, 39, SH110X_WHITE);
  display.drawLine(123, 23, 123, 39, SH110X_WHITE);
  display.drawPixel(1, 22, SH110X_WHITE);
}

static void beginText(DisplayType& display, const uint8_t* font) {
  listText.begin(display);
  listText.setFont(font);
  listText.setFontMode(1);
  listText.setForegroundColor(SH110X_WHITE);
  listText.setBackgroundColor(SH110X_BLACK);
}

static void drawLabel(DisplayType& display, byte item, int16_t y, bool primary) {
  beginText(display, primary ? u8g2_font_helvB08_tr : u8g2_font_haxrcorp4089_tr);
  listText.setCursor(25, y);
  listText.print(menuItems[item]);
}

static void renderListMenu(DisplayType& display, byte menuIndex, int16_t scrollbarY = -1) {
  display.clearDisplay();
  const byte previous = (menuIndex + 6) % 7;
  const byte next = (menuIndex + 1) % 7;
  drawIcon(display, previous, 4, 3);
  drawLabel(display, previous, 14, false);
  drawIcon(display, menuIndex, 4, 24);
  drawLabel(display, menuIndex, 35, true);
  drawIcon(display, next, 4, 47);
  drawLabel(display, next, 58, false);
  drawFrame(display);
  drawScrollbar(display, menuIndex, 7, scrollbarY);
  display.display();
}

void displayListMenu(DisplayType& display, byte menuIndex, int previousIndex) {
  const unsigned long now = millis();
  if (!animationStarted) {
    animationStarted = true;
    activeItem = menuIndex;
    animationTick = now;
  } else if (activeItem != menuIndex) {
    animationFrames[activeItem] = 0;
    animationFrames[menuIndex] = 0;
    activeItem = menuIndex;
    animationTick = now;
  } else if (now - animationTick >= 333) {
    animationTick = now;
    animationFrames[activeItem] = (animationFrames[activeItem] + 1) % menuIcons[activeItem]->frameCount;
  }

  if (previousIndex >= 0 && previousIndex < 7 && previousIndex != menuIndex) {
    const uint8_t steps = 8;
    const int16_t startY = getScrollbarY(display, previousIndex, 7);
    const int16_t endY = getScrollbarY(display, menuIndex, 7);
    for (uint8_t step = 1; step <= steps; ++step) {
      renderListMenu(
        display, menuIndex, interpolateMenuY(startY, endY, step, steps));
    }
    return;
  }

  renderListMenu(display, menuIndex);
}

void resetListMenuAnimation(byte menuIndex) {
  if (menuIndex >= 7) return;
  animationFrames[menuIndex] = 0;
  activeItem = menuIndex;
  animationTick = millis();
  animationStarted = true;
}

static void renderListSubmenu(DisplayType& display, const char* const items[],
                              byte itemCount, byte menuIndex, int16_t scrollbarY = -1) {
  const byte itemsOnScreen = 4;
  byte windowPosition = menuIndex;
  if (windowPosition > 0) --windowPosition;
  if (itemCount <= itemsOnScreen) windowPosition = 0;
  else if (windowPosition > itemCount - itemsOnScreen) windowPosition = itemCount - itemsOnScreen;

  display.clearDisplay();
  beginText(display, u8g2_font_haxrcorp4089_tr);
  for (byte position = windowPosition; position < itemCount && position < windowPosition + itemsOnScreen; ++position) {
    const byte itemPosition = position - windowPosition;
    const int16_t y = itemPosition * 16;
    if (position == menuIndex) {
      display.fillRoundRect(0, y + 1, 123, 14, 1, SH110X_WHITE);
      listText.setForegroundColor(SH110X_BLACK);
    } else {
      listText.setForegroundColor(SH110X_WHITE);
    }
    listText.setCursor(6, y + 12);
    listText.print(items[position]);
  }
  drawScrollbar(display, menuIndex, itemCount, scrollbarY);
  display.display();
}

void displayListSubmenuImpl(DisplayType& display, const char* const items[], byte itemCount,
                            byte menuIndex, int previousIndex) {
  if (previousIndex >= 0 && previousIndex < itemCount && previousIndex != menuIndex) {
    const uint8_t steps = 8;
    const int16_t startY = getScrollbarY(display, previousIndex, itemCount);
    const int16_t endY = getScrollbarY(display, menuIndex, itemCount);
    for (uint8_t step = 1; step <= steps; ++step) {
      renderListSubmenu(
        display, items, itemCount, menuIndex,
        interpolateMenuY(startY, endY, step, steps));
    }
    return;
  }

  renderListSubmenu(display, items, itemCount, menuIndex);
}
